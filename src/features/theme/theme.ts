import { asset, clientStore, editor, space } from "@silverbulletmd/silverbullet/syscalls";
import { getSsssConfig } from "../../config.ts";

/**
 * Theme switching!
 *
 * - Active theme's CSS is written in a hidden page in a `space-style`
 * - Theme colors are bundled as assets in `assets/themes/theme-<name>.css`
 */

const STORE_KEY = "ssss.theme";
const DEFAULT_THEME = "default";
const THEME_PAGE = "Library/garado/ssss/_theme";
const BUILTIN_THEME_NAMES = ["default", "nord", "nostalgia", "everforest", "gruvbox"];

async function getThemeNames(): Promise<string[]> {
  const cfg = await getSsssConfig();
  const themeCfg = cfg.theme;
  const themes = themeCfg && typeof themeCfg === "object"
    ? (themeCfg as Record<string, unknown>).themes
    : undefined;
  if (Array.isArray(themes) && themes.length > 0 && themes.every((t) => typeof t === "string")) {
    return themes as string[];
  }
  return BUILTIN_THEME_NAMES;
}

async function getCurrentTheme(): Promise<string> {
  const stored = await clientStore.get(STORE_KEY);
  return typeof stored === "string" ? stored : DEFAULT_THEME;
}

async function applyToSpace(theme: string) {
  const [themeCss, sharedCss] = await Promise.all([
    asset.readAsset("ssss", `assets/themes/theme-${theme}.css`, "utf8"),
    asset.readAsset("ssss", "assets/themes/theme-shared.css", "utf8"),
  ]);
  const page = [
    "---",
    "publish: false",
    "---",
    "",
    "Auto-generated by ssss; do not edit",
    "",
    "```space-style",
    themeCss.trim(),
    "",
    sharedCss.trim(),
    "```",
    "",
  ].join("\n");
  await space.writePage(THEME_PAGE, page);
}

async function setAndApply(theme: string) {
  await clientStore.set(STORE_KEY, theme);
  await applyToSpace(theme);
  await editor.flashNotification(`Theme: ${theme}`);
  await editor.reloadUI();
}

export async function cycleTheme() {
  const names = await getThemeNames();
  const current = await getCurrentTheme();
  const idx = names.indexOf(current);
  const next = names[(idx + 1) % names.length];
  await setAndApply(next);
}

export async function setTheme() {
  const names = await getThemeNames();
  const current = await getCurrentTheme();
  const choice = await editor.filterBox(
    "Theme",
    names.map((name) => ({ name, hint: name === current ? "current" : "" })),
    "Pick a theme to apply",
  );
  if (!choice) return;
  await setAndApply(choice.name);
}

/** Resync generated theme page on every client init */
export async function applyStoredTheme() {
  const current = await getCurrentTheme();
  await applyToSpace(current);
}

export async function toggleDarkMode() {
  const current = await editor.getUiOption("darkMode");
  await editor.setUiOption("darkMode", !current);
}
